# ---------------------------------------------------------------- 检索
def _score(query: str, rule: dict) -> float:
    """关键词命中打分：长词权重高，命中多个词加分。

    不用 BM25 是有意的——规则卡只有 6 条、关键词不到 40 个，
    在这个规模上倒排索引是纯浪费，而"长词优先"正好能解决
    「保证金比例」不该只靠「保证金」命中两融、也要能区分两融和期货的问题。
    """
    q = str(query or "").upper()
    hit = [k for k in rule["关键词"] if k.upper() in q]
    if not hit:
        return 0.0
    base = max(len(k) for k in hit)
    return base * (1 + 0.25 * (len(hit) - 1))


def lookup(query: str, limit: int = 2) -> dict:
    """按问句查规则卡。查不到就是查不到，不做模糊兜底。"""
    ranked = sorted(((r, _score(query, r)) for r in RULES), key=lambda x: -x[1])
    hits = [(r, s) for r, s in ranked if s > 0][:limit]
    if not hits:
        return {
            "命中": 0,
            "结论": ("规则卡里没有这一条。这类问题属于公开的金融常识或交易所规则，"
                   "可以直接按你掌握的知识回答，但要说明「这是通用知识，不是本系统数据」，"
                   "涉及具体数值时提醒用户以交易所/证监会最新公告为准。"),
        }

    out = []
    for r, sc in hits:
        item = {
            "科目": r["科目"],
            "摘要": r["摘要"],
            "条目": r["条目"],
        }
        if r.get("代码位置"):
            item["落在这个系统的代码"] = r["代码位置"]
        if r.get("本系统口径"):
            item["本系统口径"] = r["本系统口径"]
        stale = [x for x in r["条目"] if x.get("状态") == "待核"]
        if stale:
            item["时效警告"] = (f"其中 {len(stale)} 条标了「待核」，近年调整过。"
                            "回答时必须说明「这个参数有调整历史，请以交易所最新公告为准」，"
                            "不能把数值当定论。")
        out.append(item)

    return {
        "命中": len(out),
        "规则": out,
        "说明": ("这是本地规则卡，不是检索结果。可以直接引用，但要分清两件事："
                 "「确认」的条目可以直说；「待核」的条目必须带时间警示。"
                 "如果用户问的是这只票今天涨停没有，那是事实问题，要用行情工具，不要用规则卡推。"),
    }


def brief(query: str) -> str:
    """给 UI 工具徽标用的一行摘要。"""
    hit = lookup(query, limit=1)
    if not hit["命中"]:
        return "未收录"
    return hit["规则"][0]["科目"]


