# ---------------------------------------------------------------- 涨跌幅
# 唯一的实现。market.py 的 SQL 用 limit_case_sql() 从这里生成，不另写一份。
_GEM = ("300", "301", "302", "688", "689")   # 创业板 / 科创板：注册制，ST 不额外收窄
_BJ = ("4", "8", "92")                       # 北交所


def limit_pct(code: str, name: str) -> float:
    """涨跌停幅度（%）。

    板块优先于 ST：注册制板块（创业/科创、北交所）的 ST 股不额外收窄，
    只有沪深主板的 ST 才是 5%。顺序反了就会把 ST豆神 的 20% 记成 5%，
    而且这个错误不会报错，只会让涨停家数悄悄变大。
    """
    c = str(code or "")
    if c.startswith(_BJ):
        return 30.0
    if c.startswith(_GEM):
        return 20.0
    if "ST" in str(name or "").upper():
        return 5.0
    return 10.0


def limit_case_sql(code_expr: str, name_expr: str = "''") -> str:
    """把同一条规则翻译成 DuckDB SQL 的 CASE 片段。

    两处共用一份规则定义，差别只剩"用 Python 判"还是"用 SQL 判"。
    """
    def _in(col: str, prefixes: tuple[str, ...]) -> str:
        return " OR ".join(f"{col} LIKE '{p}%'" for p in prefixes)

    bj, gem = _in(code_expr, _BJ), _in(code_expr, _GEM)
    return (f"CASE WHEN {bj} THEN 30 "
            f"WHEN {gem} THEN 20 "
            f"WHEN upper(coalesce({name_expr},'')) LIKE '%ST%' THEN 5 "
            f"ELSE 10 END")


