"""规则卡：那些「看起来是常识、其实是会变的参数」的金融知识。

## 为什么单独做一层，而不是塞进 RAG 索引

实测结论（问句 → 现有 rag.search 的结果）：

    问「ST 股票涨跌幅限制」 → 命中「卫宁健康:关于回购股份的进展公告」→ 可信度【高】
    问「融资融券保证金比例」→ 命中「东吴证券审计报告」            → 可信度【高】

这就是把规则类知识交给关键词检索的必然结果：定义类问句的特征词（ST、涨跌幅、
比例、保证金）恰好是公告里的高频词，BM25 会给一个很高的分，然后模型拿着一份
回购公告去回答涨跌幅限制。而且它给的是「高可信度」——不是拒答，是自信地答错。

所以这里不是「知识库里没有就补进去」，而是**这类知识根本不该走检索**。
它有两个特征，决定了它该被"查表"而不是"召回"：

1. **有精确数值**，差一个点就是错的；
2. **会修订**，2015 年的保证金比例和 2023 年的不是一回事。

## 为什么不是让模型凭记忆答

模型记得住"创业板 20%"，但记不住"创业板 ST 依然是 20%，不额外收窄"，
更记不住这条规则的生效时间。它给出的答案看起来同样自信。

所以每条规则必须带三样东西：**生效日期、依据、可核对状态**。
状态是「待核」的，宁可让模型去说"这个参数近年多次调整，请以交易所最新公告为准"，
也不要给一个没有时间戳的数字——用户会把它当成永久事实。

## 为什么要有「代码位置」这个字段

因为同一份规则知识写两遍必然漂移，这不是假设，本项目里就发生过：

    src/market.py   （收盘版）  ST → 创业/科创 20，其余 5     ← 对
    src/realtime.py （实时版）  ST → 一律 5                    ← 错

实测证据：ST豆神(300010) 2026-11-02 涨 20.15%、*ST航图(688066) 涨 20.04%，
说明注册制板块的 ST 股上限仍是 20%。实时版把它们记成了 5%，于是
① 盘中涨停家数虚高（涨 5% 就算涨停）；② 行业视图里正常涨 20% 的票被当成复权失真剔掉。
而 realtime.py 的注释还写着"口径与收盘版 market.breadth 对齐"。

结论：规则只有一份定义、放在一处，SQL 从代码生成，文档从代码引用。
这个模块就是那个"一处"。
"""
